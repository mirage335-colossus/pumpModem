#include "helper_complete_apsk_metrics.hpp"

#include <cmath>
#include <complex>
#include <cstdint>
#include <iostream>
#include <numbers>
#include <stdexcept>
#include <vector>

namespace m = helper_complete_apsk_metrics;
struct Trace {
    std::uint64_t first = 0;
    std::vector<std::complex<float>> noisy, clean;
    std::vector<long double> input_dates;
    std::vector<unsigned char> supported, physically_disturbed;
    bool contains(std::uint64_t n) const { return n >= first && n - first < noisy.size(); }
    bool support(std::uint64_t n) const { return contains(n) && supported[n - first] != 0; }
};
void need(bool value, const char* why) { if (!value) throw std::runtime_error(why); }
// Generate an independent continuous-time RRC waveform with 64 complex APSK
// points and sample it on a fractional output-time grid. It is intentionally
// not generated by the evaluator's matched-filter loop.
double rrc(double t) {
    constexpr double a=.2, pi=std::numbers::pi;
    if(std::abs(t)<1e-12)return 1+a*(4/pi-1);
    if(std::abs(std::abs(t)-1/(4*a))<1e-12)
        return a/std::sqrt(2.)*((1+2/pi)*std::sin(pi/(4*a))+(1-2/pi)*std::cos(pi/(4*a)));
    return (std::sin(pi*t*(1-a))+4*a*t*std::cos(pi*t*(1+a)))/(pi*t*(1-16*a*a*t*t));
}
std::complex<double> apsk(unsigned k) {
    const unsigned point=(k*37u+11u)%64u;
    const double amplitude=.4+.4*(point/16u);
    const double phase=2*std::numbers::pi*((point%16u)+.25*(point/16u))/16.;
    return std::polar(amplitude,phase);
}
void check_fractional_apsk() {
    constexpr double fs=24000, start=38, gauge=.000003, offset=.37/fs, pi=std::numbers::pi;
    constexpr unsigned sps=80, nsamples=48000;
    double energy=0;
    for(int i=-640;i<=640;++i)energy+=std::pow(rrc(static_cast<double>(i)/sps),2);
    const double normalization=std::sqrt(energy/sps);
    Trace a; a.first=static_cast<std::uint64_t>(start*fs);a.noisy.resize(nsamples);a.clean.resize(nsamples);
    a.input_dates.resize(nsamples);a.supported.assign(nsamples,1);a.physically_disturbed.assign(nsamples,0);
    for(unsigned i=0;i<nsamples;++i) {
        const auto sample=a.first+i;
        const double t=static_cast<double>(sample)/fs+offset;
        const double position=(t-start-gauge)*fs/sps;
        const auto c=static_cast<long>(std::floor(position));
        std::complex<double> value{};
        for(long j=c-8;j<=c+8;++j)if(j>=0&&j<600&&std::abs(position-j)<=8)
            value+=apsk(static_cast<unsigned>(j))*rrc(position-j);
        value/=normalization;
        value*=std::polar(1.,2*pi*std::remainder(1600*t,1.)+2*pi*800*gauge);
        a.clean[i]={static_cast<float>(value.real()),static_cast<float>(value.imag())};
        a.noisy[i]=a.clean[i];a.input_dates[i]=sample+offset*fs;
    }
    m::Options o;o.fixed_gauge_seconds=gauge;o.output_time_offset_seconds=offset;
    const auto result=m::evaluate(a,o,1.,rrc,apsk);
    const auto& all=result.region[static_cast<unsigned>(m::Region::all)][static_cast<unsigned>(m::Selection::all)];
    need(all.symbols>560&&all.clean_evm<.04,"fractional-origin continuous APSK EVM");
    const auto slice=[&](std::size_t lo,std::size_t hi){
        Trace t;t.first=a.first+lo;
        t.noisy.assign(a.noisy.begin()+lo,a.noisy.begin()+hi);t.clean.assign(a.clean.begin()+lo,a.clean.begin()+hi);
        t.input_dates.assign(a.input_dates.begin()+lo,a.input_dates.begin()+hi);
        t.supported.assign(a.supported.begin()+lo,a.supported.begin()+hi);
        t.physically_disturbed.assign(a.physically_disturbed.begin()+lo,a.physically_disturbed.begin()+hi);return t;
    };
    const auto left=m::evaluate(slice(0,24000),o,1.,rrc,apsk);
    const auto right=m::evaluate(slice(24000,48000),o,1.,rrc,apsk);
    const auto& ls=left.region[static_cast<unsigned>(m::Region::all)][static_cast<unsigned>(m::Selection::all)];
    const auto& rs=right.region[static_cast<unsigned>(m::Region::all)][static_cast<unsigned>(m::Selection::all)];
    need(ls.symbols+rs.symbols<all.symbols&&ls.symbols+rs.symbols>500&&
         std::sqrt((ls.clean_error_power+rs.clean_error_power)/(ls.reference_power+rs.reference_power))<.04,
         "independent capture segments fabricated cross-gap footprints");
    o.output_time_offset_seconds=0;
    const auto wrong=m::evaluate(a,o,1.,rrc,apsk);
    const auto& misaligned=wrong.region[static_cast<unsigned>(m::Region::all)][static_cast<unsigned>(m::Selection::all)];
    need(misaligned.symbols>560&&misaligned.clean_evm>.09,"fractional origin error was hidden");
    std::cout << "helper_complete_apsk_fractional symbols=" << all.symbols << " evm=" << all.clean_evm
              << " wrong_origin_evm=" << misaligned.clean_evm << '\n';
}
int main() {
    try {
        Trace a; constexpr std::size_t count = 28800;
        a.clean.assign(count, {static_cast<float>(std::sqrt(80.)), 0});
        a.noisy = a.clean; a.supported.assign(count, 1);
        a.physically_disturbed.assign(count, 0); a.input_dates.resize(count);
        for (std::size_t i = 0; i < count; ++i) a.input_dates[i] = i;
        // A real received but unsupported area near a hop is still evaluated.
        for (unsigned i = 9550; i < 9650; ++i) a.supported[i] = 0;
        auto b = a;
        m::Options o; o.capture_first_seconds = 0; o.capture_end_seconds = 1.2;
        o.probe_hz = 0; o.mix_reference_hz = 0; o.first_symbol = 8; o.end_symbol = 352;
        o.other_fixed_gauge_seconds = 0;
        auto pulse = [](double x) { return x == 0 ? 1. : 0.; };
        auto symbol = [](unsigned) { return std::complex<double>{1, 0}; };
        const auto result = m::evaluate(a, o, 1., pulse, symbol, &b);
        const auto get = [](const auto& r, m::Region region, m::Selection selection) -> const m::Statistic& {
            return r.region[static_cast<unsigned>(region)][static_cast<unsigned>(selection)];
        };
        const auto& all = get(result, m::Region::all, m::Selection::all);
        const auto& good = get(result, m::Region::all, m::Selection::supported);
        const auto& uncertain = get(result, m::Region::all, m::Selection::uncertain);
        need(result.considered == 344 && result.footprint_unavailable == 0 && all.symbols == 344,
             "available APSK symbol accounting");
        need(all.symbols == good.symbols + uncertain.symbols && uncertain.symbols > 0,
             "uncertain samples were omitted");
        need(all.clean_evm < 1e-6 && all.noisy_evm < 1e-6, "known waveform EVM");
        need(all.footprint_crosses_nominal_hop > 0 && all.footprint_boundary_ambiguous >= all.footprint_crosses_nominal_hop,
             "hop-spanning footprint accounting");
        need(get(result,m::Region::boundary,m::Selection::all).symbols > 0 &&
             get(result,m::Region::interior,m::Selection::all).symbols > 0, "all dwell regions");
        need(good.symbols == get(result,m::Region::all,m::Selection::common).symbols,
             "identical common support");
        b.input_dates[12000] += .25;
        const auto mismatch = m::evaluate(a, o, 1., pulse, symbol, &b);
        need(mismatch.common_date_mismatch > 0 &&
             get(mismatch,m::Region::all,m::Selection::common).symbols < good.symbols,
             "different capture dates falsely compared");
        o.other_fixed_gauge_seconds = .001;
        const auto gauge = m::evaluate(a, o, 1., pulse, symbol, &b);
        need(gauge.common_gauge_mismatch > 0 && get(gauge,m::Region::all,m::Selection::common).symbols == 0,
             "different gauges falsely compared");
        a.physically_disturbed[100] = 3;
        const auto missing = m::evaluate(a, o, 1., pulse, symbol);
        need(missing.footprint_unavailable > 0 && get(missing,m::Region::all,m::Selection::all).symbols < all.symbols,
             "missing input was treated as a captured sample");
        a.physically_disturbed[100] = 0;
        for (unsigned i = 15000; i < count; ++i) a.input_dates[i] += 1;
        const auto gap = m::evaluate(a, o, 1., pulse, symbol);
        need(gap.footprint_unavailable > 0, "unrepresented input gap entered matched filter");
        check_fractional_apsk();
        std::cout << "helper_complete_apsk_metrics passed\n"; return 0;
    } catch (const std::exception& e) { std::cerr << e.what() << '\n'; return 1; }
}
