extern "C" ssize_t __wrap_getrandom(void* buffer,std::size_t length,unsigned int flags) {
    const auto index=probe.call++;
    if(static_cast<int>(index)==probe.fail_at){errno=EIO;return -1;}
    if(flags!=0 || (index<4 && length!=64)){probe.malformed_request=true;errno=EINVAL;return -1;}
    if(index<4)probe.times[index]=Clock::now();
    auto* output=static_cast<std::uint8_t*>(buffer);
    for(std::size_t i=0;i<length;++i) {
        const unsigned base=index==0?128U:index==1?0U:index==2?192U:index==3?64U:37U;
        output[i]=static_cast<std::uint8_t>(base+static_cast<unsigned>(i));
    }
    if(length && ((index==0 && probe.change_aes)||(index==1 && probe.change_serpent)))output[0]^=1U;
    return static_cast<ssize_t>(length);
}

