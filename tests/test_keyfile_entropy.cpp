struct Files {
    std::filesystem::path directory;
    Files() {
        auto base=std::filesystem::temp_directory_path();
        directory=base/("datapump-v4-entropy-"+std::to_string(static_cast<unsigned long>(::getpid()))+"-"+
                         std::to_string(Clock::now().time_since_epoch().count()));
        check(std::filesystem::create_directory(directory),"could not create fixture directory");
    }
    ~Files(){std::error_code ignored;std::filesystem::remove_all(directory,ignored);}
    std::filesystem::path path(std::string_view name) const {return directory/std::string(name);}
};

KeyfileGenerationOptions audio_options(bool changed=false) {
    KeyfileGenerationOptions result;
    result.audio=[changed](AudioEntropySink& sink,std::stop_token stop) {
        constexpr std::uint32_t rate=4000;
        std::array<float,256> samples{};
        std::uint64_t position=0;
        while(!sink.complete()) {
            check(!stop.stop_requested(),"unexpected cancellation in synthetic audio");
            for(auto& sample:samples) {
                const auto n=static_cast<int>((position*73U)%201U)-100;
                sample=static_cast<float>(n)/128.0F;
                if(changed && position==1234)sample=sample!=0.125F?0.125F:0.25F;
                ++position;
            }
            sink.add_samples(samples,rate);
        }
    };
    return result;
}

void same_key(const Crypto& actual,const Bytes& serpent,const Bytes& aes) {
    check(serpent.size()==64 && aes.size()==64,"independent lane fixture width");
    const auto expected=Crypto::from_independent_roots(serpent,aes);
    constexpr std::uint64_t epoch=1720000000;
    const Bytes message{'v','4','-','e','n','t','r','o','p','y'};
    for(auto purpose:{StreamPurpose::Data,StreamPurpose::Dsss,StreamPurpose::Scrambler,StreamPurpose::Fhss})
        check(actual.stream(purpose,epoch,3,96)==expected.stream(purpose,epoch,3,96),"AES waveform lane differs from independent KAT");
    check(actual.mac(message)==expected.mac(message),"AES MAC lane differs from independent KAT");
    check(actual.confidentiality_stream(epoch,15,97)==expected.confidentiality_stream(epoch,15,97),"cascade differs from independent entropy KAT");
    check(actual.confidentiality_mac(message)==expected.confidentiality_mac(message),"confidentiality authentication differs from independent entropy KAT");
    const auto child=actual.confidentiality_child(message),expected_child=expected.confidentiality_child(message);
    check(child.confidentiality_stream(epoch,0,64)==expected_child.confidentiality_stream(epoch,0,64),"child lanes differ from independent entropy KAT");
}

void assert_rounds() {
    check(probe.call>=6 && !probe.malformed_request,"unexpected system RNG request shape");
    check(probe.times[2]-probe.times[1]>=std::chrono::seconds(1),"OS entropy collection rounds were less than one second apart");
    check(probe.times[1]>=probe.times[0] && probe.times[3]>=probe.times[2],"OS entropy call order changed");
}

Crypto generate(const Files& files,std::string_view name,const KeyfileGenerationOptions& options) {
    const testing::KeyfilePolicy policy{4096,8193};
    const auto path=files.path(name);
    const auto result=testing::create_keyring(path,{"Fixture"},policy,std::nullopt,options);
    check(result.audio_used && result.warning.empty(),"valid audio did not produce audio-used result");
    assert_rounds();
    auto entries=testing::load_keyring(path,policy);
    check(entries.size()==1 && entries[0].name=="Fixture","v4 synthetic keyring failed to load");
    return entries[0].key;
}

void known_answer_and_isolation(const Files& files) {
    probe={}; const auto normal=generate(files,"normal.key",audio_options());
    same_key(normal,serpent_audio,aes_entry);
    probe={}; const auto changed=generate(files,"changed-audio.key",audio_options(true));
    same_key(changed,serpent_changed_audio,aes_entry);
    constexpr std::uint64_t epoch=1720000000;
    const Bytes message{'v','4','-','e','n','t','r','o','p','y'};
    check(normal.stream(StreamPurpose::Scrambler,epoch,0,64)==changed.stream(StreamPurpose::Scrambler,epoch,0,64),"audio changed AES waveform keystream");
    check(normal.mac(message)==changed.mac(message),"audio changed AES-only MAC");
    check(normal.confidentiality_stream(epoch,0,64)!=changed.confidentiality_stream(epoch,0,64),"changed audio did not change Serpent confidentiality");
    check(normal.confidentiality_mac(message)!=changed.confidentiality_mac(message),"changed audio did not change dual-lane authentication");
    probe={};probe.change_serpent=true;const auto changed_s=generate(files,"changed-s-os.key",audio_options());
    same_key(changed_s,serpent_changed_os,aes_entry);
    check(normal.stream(StreamPurpose::Dsss,epoch,0,64)==changed_s.stream(StreamPurpose::Dsss,epoch,0,64),"Serpent OS entropy changed AES waveform lane");
    probe={};probe.change_aes=true;const auto changed_a=generate(files,"changed-a-os.key",audio_options());
    same_key(changed_a,serpent_audio,aes_changed_os);
    check(normal.stream(StreamPurpose::Dsss,epoch,0,64)!=changed_a.stream(StreamPurpose::Dsss,epoch,0,64),"AES OS entropy did not change AES waveform lane");
}

void fallback_and_failures(const Files& files) {
    const testing::KeyfilePolicy policy{4096,8193};
    KeyfileGenerationOptions fallback;fallback.allow_audio_fallback=true;
    std::vector<std::string> progress;
    fallback.progress=[&](std::string_view message){progress.emplace_back(message);};
    probe={};
    const auto result=testing::create_keyring(files.path("fallback.key"),{"Fixture"},policy,std::nullopt,fallback);
    check(!result.audio_used && result.warning.find("Audio entropy unavailable")!=std::string::npos,"OS-only fallback lacked explicit warning");
    check(std::any_of(progress.begin(),progress.end(),[](const auto& s){return s.find("Audio entropy unavailable")!=std::string::npos;}),"OS-only warning not sent to progress callback");
    assert_rounds();
    auto fallback_key=testing::load_keyring(files.path("fallback.key"),policy);
    same_key(fallback_key.front().key,serpent_unavailable,aes_entry);

    KeyfileGenerationOptions required;
    probe={};rejects_with([&]{(void)testing::create_keyring(files.path("required.key"),{"Fixture"},policy,std::nullopt,required);},"requires fresh audio input","missing required audio was accepted");
    check(probe.call==0,"missing required provider consumed OS entropy before validation");

    auto short_audio=fallback;
    short_audio.audio=[](AudioEntropySink& sink,std::stop_token){const std::array<float,4> samples{0.1F,-0.1F,0.2F,-0.2F};sink.add_samples(samples,4000);};
    probe={}; const auto short_result=testing::create_keyring(files.path("short.key"),{"Fixture"},policy,std::nullopt,short_audio);
    check(!short_result.audio_used && !short_result.warning.empty(),"short audio did not visibly fall back");
    same_key(testing::load_keyring(files.path("short.key"),policy).front().key,serpent_unavailable,aes_entry);

    auto silent=fallback;
    silent.audio=[](AudioEntropySink& sink,std::stop_token){const std::array<float,512> samples{};sink.add_samples(samples,4000);};
    probe={};const auto silent_result=testing::create_keyring(files.path("silent.key"),{"Fixture"},policy,std::nullopt,silent);
    check(!silent_result.audio_used && !silent_result.warning.empty(),"silent audio did not visibly fall back");
    same_key(testing::load_keyring(files.path("silent.key"),policy).front().key,serpent_unavailable,aes_entry);

    auto invalid=fallback;
    invalid.audio=[](AudioEntropySink& sink,std::stop_token){const std::array<float,1> samples{std::numeric_limits<float>::quiet_NaN()};sink.add_samples(samples,4000);};
    probe={};const auto invalid_result=testing::create_keyring(files.path("invalid.key"),{"Fixture"},policy,std::nullopt,invalid);
    check(!invalid_result.audio_used && !invalid_result.warning.empty(),"invalid audio did not visibly fall back");
    same_key(testing::load_keyring(files.path("invalid.key"),policy).front().key,serpent_unavailable,aes_entry);

    invalid.allow_audio_fallback=false;
    probe={};rejects_unavailable([&]{(void)testing::create_keyring(files.path("invalid-required.key"),{"Fixture"},policy,std::nullopt,invalid);},"invalid required audio did not raise AudioEntropyUnavailable");
    check(probe.call==2,"invalid required audio did not abort before the second entropy round");
    rejects([&]{(void)testing::load_keyring(files.path("invalid-required.key"),policy);},"invalid required audio left a loadable keyfile");

    // A failure may leave an owner-only incomplete file. It must never load as
    // a usable keyfile; test-directory cleanup is separate from generation.
    auto bad=fallback;bad.audio=[](AudioEntropySink&,std::stop_token){throw Error("unexpected internal conditioner error");};
    probe={};rejects_with([&]{(void)testing::create_keyring(files.path("internal-error.key"),{"Fixture"},policy,std::nullopt,bad);},"unexpected internal conditioner error","unexpected audio failure silently fell back");
    check(probe.call==2,"unexpected audio failure did not abort before the second entropy round");
    rejects([&]{(void)testing::load_keyring(files.path("internal-error.key"),policy);},"incomplete keyfile loaded after audio error");

    std::stop_source stop;auto cancelled=fallback;cancelled.stop=stop.get_token();
    cancelled.audio=[&](AudioEntropySink&,std::stop_token){stop.request_stop();throw AudioEntropyUnavailable("cancelled source");};
    probe={};rejects_with([&]{(void)testing::create_keyring(files.path("cancelled.key"),{"Fixture"},policy,std::nullopt,cancelled);},"Keyfile generation cancelled","cancellation silently fell back");
    check(probe.call==2,"cancellation did not stop before second entropy round");
    rejects([&]{(void)testing::load_keyring(files.path("cancelled.key"),policy);},"cancelled partial keyfile loaded");

    for(int failure=0;failure<4;++failure) {
        probe={};probe.fail_at=failure;
        const auto path=files.path("rng-fail-"+std::to_string(failure)+".key");
        rejects_with([&]{(void)testing::create_keyring(path,{"Fixture"},policy,std::nullopt,audio_options());},"system random generation failed","OS RNG failure was accepted");
        check(probe.call==static_cast<unsigned>(failure+1),"OS RNG failure did not stop at the requested attempt");
        rejects([&]{(void)testing::load_keyring(path,policy);},"partial keyfile after OS failure loaded");
    }
}
