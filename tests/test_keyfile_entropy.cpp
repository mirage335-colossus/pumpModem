struct RandomProbe {
    unsigned call = 0;
    int fail_at = -1;
    bool change_aes = false;
    bool change_serpent = false;
    bool malformed_request = false;
    std::array<Clock::time_point,4> times{};
} probe;

void check(bool value, const char* message) {
    if(!value) throw std::runtime_error(message);
}

template<class Function> void rejects(Function&& function,const char* message) {
    bool rejected=false;
    try { function(); } catch(const std::exception&) { rejected=true; }
    check(rejected,message);
}

template<class Function> void rejects_unavailable(Function&& function,const char* message) {
    bool rejected=false;
    try { function(); } catch(const AudioEntropyUnavailable&) { rejected=true; }
    check(rejected,message);
}

template<class Function> void rejects_with(Function&& function,std::string_view expected,const char* message) {
    bool rejected=false;
    try { function(); } catch(const Error& error) { rejected=std::string_view(error.what()).find(expected)!=std::string_view::npos; }
    check(rejected,message);
}

Bytes hex(std::string_view value) {
    check(value.size()%2==0,"odd fixture hex");
    auto digit=[](char c)->unsigned {
        if(c>='0'&&c<='9') return static_cast<unsigned>(c-'0');
        if(c>='a'&&c<='f') return static_cast<unsigned>(c-'a'+10);
        throw std::runtime_error("invalid fixture hex");
    };
    Bytes result(value.size()/2);
    for(std::size_t i=0;i<result.size();++i)result[i]=static_cast<std::uint8_t>((digit(value[2*i])<<4)|digit(value[2*i+1]));
    return result;
}

