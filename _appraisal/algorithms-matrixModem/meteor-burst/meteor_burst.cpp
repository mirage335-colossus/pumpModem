// Meteor-burst link arithmetic for the Matrix Modem FSK appraisal. Theoretical calculation.
//
// Underdense-trail received power, decay time and noise from ITU-R P.843-1 (eqs. 3-15) and ITU-R P.372
// (galactic noise, eq. 13). Trail-rate anchor: Spann 1987 (50.05 MHz, 500 W, 17 dBi at each end, 1300 km,
// about 450 trails an hour above a -125 dBm floor), with the P.843 law N(q > q0) proportional to 1/q0.
// Assumptions: trail above the path midpoint at the P.843 mean height, trail axis normal to the propagation
// plane (beta = 90 deg), sin^2(alpha) = 1, initial-radius loss a1 included, a2(t0) and absorption a3 left
// out (both make the result optimistic). Underdense formula used up to q = 2e14 electrons/m only; section 5 treats
// overdense trails with the Hines-Forsyth form as reproduced in secondary sources.
//
// Build: g++ -O2 -std=c++20 meteor_burst.cpp -o meteor_burst
// Run:   ./meteor_burst > results/meteor_burst.md
#include <cmath>
#include <cstdio>
#include <initializer_list>
static const double PI = 3.14159265358979323846, RE = 2.8179e-15, AE = 6371e3, C0 = 299792458.0;
static double db(double x) { return 10 * std::log10(x); }
struct Geo { double h, D, r0, R, sec2, Tun, loss14_db; };   // loss for q = 1e14 e/m between isotropic antennas
static Geo geo(double fMHz, double dkm) {
    Geo g; double lam = C0 / (fMHz * 1e6);
    double hkm = -17 * std::log10(fMHz) + 124; g.h = hkm * 1e3;
    g.D = std::pow(10, 0.067 * hkm - 5.6); g.r0 = std::pow(10, 0.035 * hkm - 3.45);
    double th = dkm * 1e3 / (2 * AE);
    g.R = std::sqrt(AE * AE + (AE + g.h) * (AE + g.h) - 2 * AE * (AE + g.h) * std::cos(th));
    double cphi = ((AE + g.h) - AE * std::cos(th)) / g.R; g.sec2 = 1 / (cphi * cphi);
    g.Tun = lam * lam * g.sec2 / (16 * PI * PI * g.D);
    double a1 = std::exp(-8 * PI * PI * g.r0 * g.r0 / (lam * lam * g.sec2));
    double p = lam * lam * lam * RE * RE * 1e28 * a1 / (16 * PI * PI * g.R * g.R * 2 * g.R);
    g.loss14_db = -db(p); return g;
}
static double n0_dbm(double fMHz) { return -174 + 52 - 23 * std::log10(fMHz); }
int main() {
    printf("# Meteor burst at milliwatt power: link arithmetic\n\n");
    printf("Generated by `meteor_burst.cpp`. Theoretical calculation from ITU-R P.843-1 and P.372, with the trail\n");
    printf("rate anchored to one measured link (Spann 1987). Assumptions are in the program header; they favour the\n");
    printf("link. Underdense trails only, up to q = 2e14 electrons/m.\n\n");
    printf("## 1. Path loss for the strongest underdense class, decay time and noise\n\n");
    printf("| f (MHz) | path (km) | trail height (km) | loss at q = 1e14 (dB) | power decay time T_un (s) | galactic N0 (dBm/Hz) |\n|---:|---:|---:|---:|---:|---:|\n");
    for (double f : {30.0, 40.0, 50.0, 144.0}) for (double d : {500.0, 1000.0, 1300.0}) {
        Geo g = geo(f, d); printf("| %.0f | %.0f | %.1f | %.1f | %.2f | %.1f |\n", f, d, g.h / 1e3, g.loss14_db, g.Tun, n0_dbm(f));
    }
    printf("\nPower falls by 8.7 dB in T_un. Measured time constants at 50 MHz were 60 to 109 ms (Spann 1987), far\nshorter than T_un at long range, so both T_un and 0.1 s are carried below. The 144 MHz noise is an\nextrapolation of the P.372 galactic formula.\n\n");
    printf("## 2. Peak C/N0 from a q = 1e14 trail\n\n");
    printf("| f (MHz) | path (km) | power | 0 dBi each end | 10 dBi each end | 17 dBi each end |\n|---:|---:|---|---:|---:|---:|\n");
    for (double f : {40.0, 50.0}) for (double d : {500.0, 1300.0}) for (double pm : {2.0, 100.0, 100000.0}) {
        Geo g = geo(f, d); printf("| %.0f | %.0f | %s |", f, d, pm == 2 ? "2 mW" : pm == 100 ? "100 mW" : "100 W");
        for (double G : {0.0, 10.0, 17.0}) printf(" %+.1f dB-Hz |", db(pm) + 2 * G - g.loss14_db - n0_dbm(f));
        printf("\n");
    }
    printf("\nA weaker trail gives 20 log10(q / 1e14) dB less.\n\n");
    printf("## 3. Trails that deliver one tone's worth of energy, and how often\n\n");
    printf("A burst is counted as usable when its whole energy over the noise density reaches 12 dB, about what one\n");
    printf("256-value tone needs. Burst energy = peak C/N0 x (decay time / 2). `q needed` is the line density that\n");
    printf("reaches it; `none` means it exceeds 2e14, so no underdense trail does. Rate: 450 trails an hour above\n");
    printf("q = %.2g on the anchor link, scaled as 1/q; the anchor's 17 dBi beams and 1300 km path are kept for every row,\n", 1e14 * std::pow(10, (-125 - (57 + 34 - geo(50.05, 1300).loss14_db)) / 20));
    printf("which flatters small antennas in level but not in sky coverage. 50 MHz, 1300 km.\n\n");
    Geo g = geo(50.0, 1300.0); double qa = 1e14 * std::pow(10, (-125 - (57 + 34 - geo(50.05, 1300).loss14_db)) / 20), K = 450 * qa;
    printf("| power | gain each end | decay time | q needed (e/m) | usable bursts per hour | mean wait |\n|---|---:|---:|---:|---:|---|\n");
    for (double pm : {2.0, 100.0, 10000.0, 100000.0}) for (double G : {0.0, 10.0, 17.0}) for (double T : {g.Tun, 0.1}) {
        double cn14 = db(pm) + 2 * G - g.loss14_db - n0_dbm(50.0), need = 12 - db(T / 2), q = 1e14 * std::pow(10, (need - cn14) / 20);
        printf("| %s | %.0f dBi | %.2f s |", pm == 2 ? "2 mW" : pm == 100 ? "100 mW" : pm == 10000 ? "10 W" : "100 W", G, T);
        if (q > 2e14) printf(" none | 0 | - |\n"); else { double r = K / q; printf(" %.2g | %.1f | %s%.1f %s |\n", q, r, "", r >= 60 ? 3600 / r : 60 / r, r >= 60 ? "s" : "min"); }
    }
    printf("\n## 4. Average signal energy from all underdense trails\n\n");
    printf("With N(q > q0) = K/q0, the energy arriving per second is K (E14 / 1e28) (q_max - q_min), where E14 is the\n");
    printf("burst energy over N0 at q = 1e14. It is dominated by the strongest trails. `equivalent C/N0` is that\n");
    printf("energy rate with q_max = 2e14: the level of a steady signal delivering the same energy. A receiver that\n");
    printf("adds tones as energies gets less than this from the many weak bursts. 50 MHz, 1300 km.\n\n");
    printf("| power | gain each end | decay time | equivalent C/N0 |\n|---|---:|---:|---:|\n");
    for (double pm : {2.0, 100.0}) for (double G : {0.0, 10.0, 17.0}) for (double T : {g.Tun, 0.1}) {
        double cn14 = db(pm) + 2 * G - g.loss14_db - n0_dbm(50.0), e14 = std::pow(10, cn14 / 10) * T / 2;
        printf("| %s | %.0f dBi | %.2f s | %+.1f dB-Hz |\n", pm == 2 ? "2 mW" : "100 mW", G, T, db(K / 3600 * e14 / 1e28 * 2e14));
    }
    printf("\n## 5. Overdense trails\n\n");
    printf("Hines-Forsyth form as reproduced in two secondary sources (see the research note):\n");
    printf("P(t) = P G G lambda^2 / [32 pi^2 R1 R2 (R1+R2)] x sqrt{ (x / sec^2 phi) ln(a / x) }, x = 4 D t + r0^2,\n");
    printf("a = re q lambda^2 sec^2 phi / pi^2. Peak = P G G lambda^3 sqrt(re q) / [32 pi^3 sqrt(e) R1 R2 (R1+R2)], reached at\n");
    printf("x = a/e; the echo ends at x = a (duration T_ov). The underdense and overdense formulas do not join: at\n");
    printf("q = 2e14 the overdense peak is 6.4 dB below the underdense one. Durations are cut at 15 s and at 3 s as\n");
    printf("well, because wind distortion and electron loss end real echoes early (the longest seen on a measured\n");
    printf("45 MHz link exceeded 40 s, very rarely, and few lasted over 1 s between fades). Fading inside the echo is\n");
    printf("not modelled. Rate as in section 3 (anchor link, 1/q). 50 MHz, 100 mW, 0 dBi at each end, galactic noise;\n");
    printf("add 20 log10 of other power and gain ratios in dB to the level and energy columns.\n\n");
    for (double d : {1300.0, 500.0}) {
        Geo g = geo(50.0, d); double lam = C0 / 50e6, R = g.R;
        printf("**Path %.0f km** (rate %s).\n\n", d, d == 1300 ? "of the anchor link" : "about a quarter of the anchor link's, as measured on a 520 km path; the column uses that");
        printf("| q (e/m) | trails an hour above q | peak C/N0 | T_ov | energy over N0: whole echo | cut at 15 s | cut at 3 s |\n|---:|---:|---:|---:|---:|---:|---:|\n");
        for (double q : {2e14, 5e14, 1e15, 3e15, 1e16, 3e16}) {
            double peak = 0.1 * lam * lam * lam * std::sqrt(RE * q) / (32 * PI * PI * PI * std::sqrt(std::exp(1.0)) * R * R * 2 * R);   // W
            double cn = db(peak * 1e3) - n0_dbm(50.0), aa = RE * q * lam * lam * g.sec2 / (PI * PI), Tov = (aa - g.r0 * g.r0) / (4 * g.D);
            auto energy = [&](double cap) { double T = std::min(cap, Tov), e = 0; int n = 20000; for (int i = 0; i < n; ++i) { double t = (i + 0.5) * T / n, x = 4 * g.D * t + g.r0 * g.r0; e += std::sqrt(std::max(0.0, x * std::log(aa / x)) / (aa / std::exp(1.0))); } return std::pow(10, cn / 10) * e * T / n; };
            printf("| %.0e | %.2f | %+.1f dB-Hz | %.1f s | %.1f dB | %.1f dB | %.1f dB |\n", q, K / q * (d == 1300 ? 1 : 110.0 / 450), cn, Tov, db(energy(1e9)), db(energy(15)), db(energy(3)));
        }
        printf("\n");
    }
    printf("For scale: one 256-value tone needs about 12 dB, and a 10-bit block received per tone on a steady path\nabout 20 dB (32 tones); a fading echo needs more.\n\n");
    return 0;
}
