// Meteor trails over the whole shared sky of two stations: how many deliver a tone's or a block's worth of
// energy to a low-power link, against the distance between the stations. Theoretical calculation (Monte Carlo
// over trail position and direction; formulas as in meteor_burst.cpp).
//
// Model. Spherical Earth. Trails are straight, 25 km long (15-50 km in the literature), centred at 95 km.
// Meteor flux through a horizontal area: 160/q0 per m^2 per second above line density q0 (ITU-R P.843-1),
// continued to 1e16 electrons/m; trails that would need more are not counted. Directions follow the flux
// through a horizontal surface from an isotropic sky (pdf proportional to cos z sin z). A trail is usable
// when the forward-scatter condition u.(rT + rR) = 0 is met at a point on it that both stations see at
// 3 degrees elevation or more. Underdense formula below q = 7.5e13 (where the two peak formulas cross),
// Hines-Forsyth overdense form above, echo cut at 15 s. 50 MHz, galactic noise, transmit gain 0 dBi, the
// receive gain applied in every direction (an array forming all beams). Fading, absorption, polarization
// loss and the trail-formation loss are left out; the annual-average flux is used.
//
// Build: g++ -O2 -std=c++20 -fopenmp meteor_sky.cpp -o meteor_sky
// Run:   ./meteor_sky [samples, default 4000000] > results/meteor_sky.md
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <vector>
#include <omp.h>
static const double PI = 3.14159265358979323846, RE = 2.8179e-15, AE = 6371e3, C0 = 299792458.0, LAM = C0 / 50e6;
static double db(double x) { return 10 * std::log10(x); }
struct V { double x, y, z; };
static V operator+(V a, V b) { return {a.x + b.x, a.y + b.y, a.z + b.z}; }
static V operator-(V a, V b) { return {a.x - b.x, a.y - b.y, a.z - b.z}; }
static V operator*(double k, V a) { return {k * a.x, k * a.y, k * a.z}; }
static double dot(V a, V b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
static double nrm(V a) { return std::sqrt(dot(a, a)); }
static V unit(V a) { return (1 / nrm(a)) * a; }
static V cross(V a, V b) { return {a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x}; }
struct Rng { uint64_t s; double uni() { s += 0x9E3779B97F4A7C15ull; uint64_t z = s; z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ull; z = (z ^ (z >> 27)) * 0x94D049BB133111EBull; z ^= z >> 31; return ((z >> 11) + 0.5) / 9007199254740992.0; } };
struct Tr { double R1, R2, sec2, gf, D, r0; bool mono; };   // geometry of one usable trail
// energy over N0 (linear), peak C/N0 (linear) and duration for line density q; pg = power (W) x gains
static void echo(const Tr& t, double q, double pg, double n0w, double& E, double& peak, double& T) {
    double den = t.R1 * t.R2 * (t.R1 + t.R2) * t.gf, a = RE * q * LAM * LAM * t.sec2 / (PI * PI);
    double Tov = (a - t.r0 * t.r0) / (4 * t.D);
    if (q < 7.5e13 || Tov <= 0) {
        double a1 = std::exp(-8 * PI * PI * t.r0 * t.r0 / (LAM * LAM * t.sec2));
        peak = pg * LAM * LAM * LAM * RE * RE * q * q * a1 / (16 * PI * PI * den) / n0w;
        T = LAM * LAM * t.sec2 / (16 * PI * PI * t.D); E = peak * T / 2; return;
    }
    peak = pg * LAM * LAM * LAM * std::sqrt(RE * q) / (32 * PI * PI * PI * std::sqrt(std::exp(1.0)) * den) / n0w;
    T = std::min(Tov, 15.0); double e = 0; const int n = 120;
    for (int i = 0; i < n; ++i) { double tt = (i + 0.5) * T / n, x = 4 * t.D * tt + t.r0 * t.r0; e += std::sqrt(std::max(0.0, x * std::log(a / x)) / (a / std::exp(1.0))); }
    E = peak * e * T / n;
}
int main(int argc, char** argv) {
    long N = argc > 1 ? std::atol(argv[1]) : 4000000;
    const double h = 95e3, L = 25e3, n0w = std::pow(10, (-174 + 52 - 23 * std::log10(50.0)) / 10) * 1e-3, elmin = std::sin(3 * PI / 180);
    printf("# Meteor trails over the whole shared sky: usable trails against station distance\n\n");
    printf("Generated by `meteor_sky.cpp` with %ld sampled trails per distance. Theoretical calculation; the model and\n", N);
    printf("what it leaves out are in the program header. 50 MHz, galactic noise, 0 dBi at the transmitter, the\n");
    printf("receive gain available in every direction. A tone's worth is 12 dB of echo energy over the noise density,\n");
    printf("a block's worth 20 dB, and 26 dB allows 6 dB for fading inside the echo.\n\n");
    struct Cfg { const char* name; double pg; };
    const Cfg cfg[] = {{"100 mW, 0 dBi receive", 0.1}, {"100 mW, 10 dBi", 1.0}, {"100 mW, 20 dBi", 10.0}, {"2 mW, 0 dBi", 0.002}, {"2 mW, 10 dBi", 0.02}, {"2 mW, 20 dBi", 0.2}};
    const double thr[] = {12, 20, 26};
    for (int pass = 0; pass < 2; ++pass) {
        if (pass == 0) { printf("## 1. Check against the measured long link\n\n");
            printf("Spann 1987 counted about 450 trails an hour above -125 dBm with 500 W and 17 dBi beams at each end over\n1,300 km. The model, with 17 dBi applied over the whole sky, gives the figure below; the real beams covered\nonly part of the sky, so the model should come out higher.\n\n"); }
        else printf("## 2. Usable trails an hour\n\n");
        for (double Bkm : pass == 0 ? std::vector<double>{1300} : std::vector<double>{50, 150, 300, 500, 1000, 1300}) {
            double th = Bkm * 1e3 / (2 * AE); V Tx = {-AE * std::sin(th), 0, AE * std::cos(th)}, Rx = {AE * std::sin(th), 0, AE * std::cos(th)};
            double psimax = th + 1250e3 / AE, area = 2 * PI * (AE + h) * (AE + h) * (1 - std::cos(psimax));
            double rate[6][3] = {}, wT[6][3] = {}, wmono[6][3] = {}, wR[6][3] = {}, spec = 0, chk = 0;
            #pragma omp parallel
            {
                double lr[6][3] = {}, lT[6][3] = {}, lm[6][3] = {}, lR[6][3] = {}, ls = 0, lc = 0;
                #pragma omp for schedule(static)
                for (long i = 0; i < N; ++i) {
                    Rng r{(uint64_t)(i * 0x9E3779B97F4A7C15ull + (uint64_t)Bkm * 7919 + 17)};
                    double cz = 1 - r.uni() * (1 - std::cos(psimax)), sz = std::sqrt(1 - cz * cz), az = 2 * PI * r.uni();
                    V up = {sz * std::cos(az), sz * std::sin(az), cz}, Cc = (AE + h) * up;
                    V e1 = unit(cross(up, std::fabs(up.z) < 0.9 ? V{0, 0, 1} : V{1, 0, 0})), e2 = cross(up, e1);
                    double cth = std::sqrt(r.uni()), sth = std::sqrt(1 - cth * cth), al = 2 * PI * r.uni();
                    V u = sth * std::cos(al) * e1 + sth * std::sin(al) * e2 - cth * up;
                    auto f = [&](double s) { V P = Cc + s * u; return dot(u, unit(Tx - P) + unit(Rx - P)); };
                    double a = -L / 2, b = L / 2, fa = f(a), fb = f(b); if (fa * fb > 0) continue;
                    for (int k = 0; k < 40; ++k) { double m = 0.5 * (a + b), fm = f(m); if (fa * fm <= 0) { b = m; } else { a = m; fa = fm; } }
                    V P = Cc + 0.5 * (a + b) * u, pt = Tx - P, pr = Rx - P; double R1 = nrm(pt), R2 = nrm(pr);
                    if (dot(-1.0 * pt, unit(Tx)) / R1 < elmin || dot(-1.0 * pr, unit(Rx)) / R2 < elmin) continue;
                    V ut = unit(pt), ur = unit(pr); double c2 = std::clamp(dot(ut, ur), -1.0, 1.0), cphi2 = 0.5 * (1 + c2), sphi2 = 1 - cphi2;
                    V dd = ut - ur; double cb = nrm(dd) > 1e-9 ? dot(u, unit(dd)) : 0, hk = (nrm(P) - AE) / 1e3;
                    Tr t{R1, R2, 1 / std::max(cphi2, 1e-6), 1 - cb * cb * sphi2, std::pow(10, 0.067 * hk - 5.6), std::pow(10, 0.035 * hk - 3.45), false};
                    { V Pa = Cc + (-L / 2) * u, Pb = Cc + (L / 2) * u; t.mono = dot(u, unit(Tx - Pa)) * dot(u, unit(Tx - Pb)) <= 0; }
                    ls += 1;
                    if (pass == 0) {   // peak above -125 dBm with 500 W and 17 dBi at each end
                        double need = std::pow(10, -12.5) * 1e-3 / n0w, lo = 1e10, hi = 1e16, E, pk, T; echo(t, hi, 500 * 2500, n0w, E, pk, T);
                        if (pk < need) continue;
                        for (int k = 0; k < 50; ++k) { double m = std::sqrt(lo * hi); echo(t, m, 500 * 2500, n0w, E, pk, T); if (pk >= need) hi = m; else lo = m; }
                        lc += 160 / hi; continue;
                    }
                    for (int c = 0; c < 6; ++c) for (int j = 0; j < 3; ++j) {
                        double need = std::pow(10, thr[j] / 10), lo = 1e11, hi = 1e16, E, pk, T; echo(t, hi, cfg[c].pg, n0w, E, pk, T);
                        if (E < need) continue;
                        for (int k = 0; k < 44; ++k) { double m = std::sqrt(lo * hi); echo(t, m, cfg[c].pg, n0w, E, pk, T); if (E >= need) hi = m; else lo = m; }
                        echo(t, hi, cfg[c].pg, n0w, E, pk, T); double w = 160 / hi;
                        lr[c][j] += w; lT[c][j] += w * T; lm[c][j] += w * t.mono; lR[c][j] += w * 0.5 * (R1 + R2);
                    }
                }
                #pragma omp critical
                { spec += ls; chk += lc; for (int c = 0; c < 6; ++c) for (int j = 0; j < 3; ++j) { rate[c][j] += lr[c][j]; wT[c][j] += lT[c][j]; wmono[c][j] += lm[c][j]; wR[c][j] += lR[c][j]; } }
            }
            double k = area / N * 3600;
            if (pass == 0) { printf("Model, whole sky: %.0f trails an hour above -125 dBm. Usable-orientation fraction of sampled trails: %.1f%%.\n\n", chk * k, 100 * spec / N); continue; }
            printf("**%.0f km between the stations** (%.1f%% of sampled trails meet the scatter condition in view of both).\n\n", Bkm, 100 * spec / N);
            printf("| power and receive gain | a tone's worth | a block's worth | block with 6 dB for fading | mean echo length at the block threshold | mean trail distance | of those, also in line for a radar at the transmitter |\n|---|---:|---:|---:|---:|---:|---:|\n");
            for (int c = 0; c < 6; ++c) {
                printf("| %s | %.2f | %.2f | %.2f |", cfg[c].name, rate[c][0] * k, rate[c][1] * k, rate[c][2] * k);
                if (rate[c][1] > 0) printf(" %.1f s | %.0f km | %.0f%% |\n", wT[c][1] / rate[c][1], wR[c][1] / rate[c][1] / 1e3, 100 * wmono[c][1] / rate[c][1]); else printf(" - | - | - |\n");
            }
            printf("\n");
        }
    }
    printf("Rates are trails an hour. `In line for a radar` counts trails that also have a point, within their\n25 km, at right angles to the line of sight from the transmitting site, so that a radar there would get a\nspecular echo from the same trail.\n");
    return 0;
}
