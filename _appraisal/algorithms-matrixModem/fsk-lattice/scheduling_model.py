#!/usr/bin/env python3
"""Model check of scheduling rules for the FSK lattice receiver (theoretical; derived from measured rates).

Uses the stage rates measured on a full RTX PRO 6000 Blackwell and a 13.6-CPU host
(results/gpu/chunks.out, contend.out, decode_16.out) as costs, and asks how long each rule takes to
clear a queued workload. It is arithmetic on measured costs, not a running scheduler.

Run:  python3 -I scheduling_model.py > results/scheduling_model.md
"""

# measured, dwells per second for the 352 tone positions (route alone on the device)
GPU_TRANSFORM = {
    ("cuFFT", 4096): 200.57e6, ("cuFFT", 32768): 77.74e6,
    ("FP16 matrix DFT", 4096): 96.60e6, ("FP16 matrix DFT", 32768): 94.17e6,
    ("INT8 matrix DFT", 4096): 31.58e6, ("INT8 matrix DFT", 32768): 59.83e6,
}
CPU_TRANSFORM = 1.82e6        # plain radix-2 FFT on 13 host threads, 32,768 dwells per call
GPU_DECODE = 8234.0           # direct kernel, full 24-bit decodes per second
GPU_DECODE_MATRIX = 5024.0    # FP16 matrix-product decode

# measured together (contend.out): (search route, transform route) -> (decodes/s, transform dwells/s)
SHARED = {
    ("direct", "cuFFT"): (7069, 7.2466e6), ("direct", "FP16 matrix DFT"): (7250, 7.4244e6),
    ("direct", "INT8 matrix DFT"): (6930, 7.0961e6),
    ("matrix", "cuFFT"): (4249, 13.0564e6), ("matrix", "FP16 matrix DFT"): (4463, 13.7147e6),
    ("matrix", "INT8 matrix DFT"): (4082, 12.5554e6),
}


def human(t):
    if t < 1:
        return "%.1f ms" % (t * 1e3)
    if t < 120:
        return "%.2f s" % t
    return "%.1f min" % (t / 60)


def main():
    print("# Scheduling rules against measured stage costs\n")
    print("Generated by `scheduling_model.py`. Arithmetic on the rates measured on a full RTX PRO 6000")
    print("Blackwell with a 13.6-CPU host; not a running scheduler. Theoretical calculation.\n")

    print("## 1. Is a shared GPU work-conserving?\n")
    print("Each stage's rate while sharing, divided by its rate alone (32,768 dwells per call), and the sum.")
    print("A sum of 1 means the GPU time was divided, not lost.\n")
    print("| Search route | Transform route | search share | transform share | sum |")
    print("|---|---|---:|---:|---:|")
    for (srch, tr), (dec, dw) in SHARED.items():
        a = dec / (GPU_DECODE if srch == "direct" else GPU_DECODE_MATRIX)
        b = dw / GPU_TRANSFORM[(tr, 32768)]
        print("| %s | %s | %.3f | %.3f | %.3f |" % (srch, tr, a, b, a + b))
    print()

    best_route = max(GPU_TRANSFORM, key=GPU_TRANSFORM.get)
    race_route = ("FP16 matrix DFT", 32768)   # what the prototype race chose in every load
    print("## 2. Time to clear a queued workload\n")
    print("A workload is a number of dwell transforms (dwells times timing hypotheses) and a number of full")
    print("block decodes. The GPU is taken as work-conserving (section 1: within about 5%). The CPU has no")
    print("measured decode route, so it can only take transforms. Rules:\n")
    print("- `stage race`: what the prototype did. Transform on the GPU by the route that won the 0.5 s race")
    print("  under load (%s at %d per call), decode on the GPU, CPU idle." % race_route)
    print("- `CPU FFT, GPU search`: a fixed rule. All transforms on the CPU, all decodes on the GPU.")
    print("- `cost-based`: each stage on the GPU by its cheapest measured route and portion size (%s at %d" % best_route)
    print("  per call), with the CPU taking transform portions whenever it is free.\n")
    for scale, label in ((1.0, "measured device"), (0.01, "hypothetical GPU 100 times slower, same CPU")):
        gt_best = GPU_TRANSFORM[best_route] * scale
        gt_race = GPU_TRANSFORM[race_route] * scale
        gd = GPU_DECODE * scale
        print("**%s**\n" % (label[0].upper() + label[1:]))
        print("| Workload | dwell transforms | decodes | stage race | CPU FFT, GPU search | cost-based | worst rule / cost-based |")
        print("|---|---:|---:|---:|---:|---:|---:|")
        loads = (
            ("one block at 0 dB-Hz", 1500 * 9, 400),
            ("one block at -10 dB-Hz", 127000 * 9, 400),
            ("one block at -20 dB-Hz", 14.5e6 * 9, 400),
            ("1,000 simulated blocks at -10 dB-Hz", 127000 * 9 * 1000, 400 * 1000),
        )
        for name, T, H in loads:
            a = T / gt_race + H / gd
            b = max(T / CPU_TRANSFORM, H / gd)
            # cost-based: the CPU takes transform portions for the whole time; the GPU does the rest
            c = (T / gt_best + H / gd) / (1 + CPU_TRANSFORM / gt_best)
            if CPU_TRANSFORM * c > T:          # the CPU alone covers the transforms; the GPU only decodes
                c = max(T / CPU_TRANSFORM, H / gd)
            print("| %s | %.3g | %.3g | %s | %s | %s | %.1f |" % (name, T, H, human(a), human(b), human(c), max(a, b) / c))
        print()
    print("Limits: stage precedence inside a block, queue memory, transfer time and the 5% sharing error are")
    print("ignored. The hypothetical device only scales the measured GPU rates; nothing was measured on it.")


if __name__ == "__main__":
    main()
