// Finite-message penalty relative to the ergodic peak-limited bound.
//
// For the spread-matched long-dwell tone receiver (weighted periodogram = asymptotic
// estimator-correlator) the information density of the transmitted hypothesis over a message of
// duration D is a sum over frequency bins of independent terms lam_k u_k - ln(1+lam_k), with
// u_k ~ Exp(1) and lam_k = P S(f_k) on a 1/D grid (fading and noise randomness both included).
//   mean = D [P - Integral ln(1+P S)]   (the bound times D)
//   var  = D P^2 Integral S^2 = D P^2 / B_eff
// A k-bit message decoded by an infinite-alphabet code fails roughly when the accumulated density
// falls below k ln 2 (dependence-testing / normal-approximation heuristic; not a converse).
// For a flat Doppler spectrum of width B the density is x*Gamma(n) - n ln(1+x) with n = D*B and
// x = P/B, so the CDF is an exact regularized incomplete gamma. For a Gaussian spectrum the sum is
// matched by a Gamma law with the same mean and variance (shifted by the deterministic part).
// Output: required duration relative to the ergodic duration k ln2 / R, in dB (= extra energy).
//
// Build: g++ -O2 -std=c++20 finite_message.cpp -o finite_message
#include <cmath>
#include <cstdio>
#include <vector>

static const double PI = 3.14159265358979323846, LN2 = 0.69314718055994530942;
static double db(double x) { return 10 * std::log10(x); }
static double undb(double x) { return std::pow(10.0, x / 10); }

// regularized lower incomplete gamma P(a, x)
static double gammp(double a, double x) {
    if (x <= 0) return 0;
    double gln = std::lgamma(a);
    if (x < a + 1) {
        double ap = a, sum = 1 / a, del = sum;
        for (int n = 0; n < 100000; ++n) { ap += 1; del *= x / ap; sum += del; if (std::fabs(del) < std::fabs(sum) * 1e-15) break; }
        return sum * std::exp(-x + a * std::log(x) - gln);
    }
    double b = x + 1 - a, c = 1e300, d = 1 / b, h = d;
    for (int i = 1; i < 100000; ++i) {
        double an = -i * (i - a); b += 2; d = an * d + b; if (std::fabs(d) < 1e-300) d = 1e-300;
        c = b + an / c; if (std::fabs(c) < 1e-300) c = 1e-300; d = 1 / d; double del = d * c; h *= del;
        if (std::fabs(del - 1) < 1e-15) break;
    }
    return 1 - std::exp(-x + a * std::log(x) - gln) * h;
}

// Flat spectrum, x = energy per bin (= P/B), n bins (= D*B): P(x*G(n) - n ln(1+x) < K)
static double fail_flat(double x, double n, double K) { return gammp(n, (K + n * std::log1p(x)) / x); }

// Gaussian spectrum (2sigma = 1 after scaling): moments per unit "duration*B_eff".
struct GM { double mean, var, det; };  // per bin-density unit: mean of sum lam u, var, deterministic sum ln(1+lam)
static GM gauss_moments(double xP) {  // xP = P / B_eff ; S normalized with B_eff = 1
    // Gaussian S with B_eff = 1: sigma = 1/(2 sqrt(pi))
    double sig = 1 / (2 * std::sqrt(PI));
    double lo = -14 * sig, hi = 14 * sig; int n = 200000; double h = (hi - lo) / n;
    double m = 0, v = 0, d = 0;
    for (int i = 0; i <= n; ++i) {
        double f = lo + i * h, S = std::exp(-0.5 * f * f / (sig * sig)) / (std::sqrt(2 * PI) * sig);
        double w = (i == 0 || i == n) ? 1 : (i % 2 ? 4 : 2), lam = xP * S;
        m += w * lam; v += w * lam * lam; d += w * std::log1p(lam);
    }
    return {m * h / 3, v * h / 3, d * h / 3};
}
// P(sum lam u - det*D < K) with D in units of 1/B_eff, Gamma moment match
static double fail_gauss(const GM& g, double D, double K) {
    double mean = g.mean * D, var = g.var * D;
    double shape = mean * mean / var, scale = var / mean;
    return gammp(shape, (K + g.det * D) / scale);
}

int main() {
    printf("# Finite-message penalty relative to the ergodic bound\n\n");
    printf("Generated by `finite_message.cpp`. x = (C/N0)/B_eff is the received energy per effective\n");
    printf("coherence interval (B_eff = 1/∫S²). Entries: extra transmit time (= energy at fixed power) in dB\n");
    printf("needed so that a k-bit message fails with probability at most ε, relative to the ergodic time\n");
    printf("k·ln2/R. In parentheses: the number of effective coherence intervals D·B_eff spanned by the message.\n");
    printf("Spread-matched long-dwell tone receiver; information-density heuristic (see source).\n\n");
    for (int shape = 0; shape < 2; ++shape) {
        printf("## %s Doppler spectrum\n\n", shape == 0 ? "Gaussian" : "Flat (exact Gamma law)");
        for (double eps : {0.1, 0.01, 0.001}) {
            printf("**ε = %g**\n\n| x (dB) | k = 20 bits | 100 bits | 1000 bits | 10000 bits |\n|---:|---:|---:|---:|---:|\n", eps);
            for (double xdb : {-20.0, -10.0, 0.0, 10.0, 20.0, 30.0}) {
                double x = undb(xdb);
                printf("| %+.0f |", xdb);
                for (double k : {20.0, 100.0, 1000.0, 10000.0}) {
                    double K = k * LN2;
                    double Rerg, Dlo, Dhi;
                    GM g{};
                    if (shape == 1) { Rerg = x - std::log1p(x); }  // per unit D*B
                    else { g = gauss_moments(x); Rerg = g.mean - g.det; }
                    double D0 = K / Rerg;
                    auto fail = [&](double D) { return shape == 1 ? fail_flat(x, D, K) : fail_gauss(g, D, K); };
                    Dlo = D0 * 0.5; Dhi = D0;
                    while (fail(Dhi) > eps) Dhi *= 1.5;
                    for (int it = 0; it < 200; ++it) { double mid = 0.5 * (Dlo + Dhi); if (fail(mid) > eps) Dlo = mid; else Dhi = mid; }
                    printf(" %.2f (%.3g) |", db(Dhi / D0), Dhi);
                }
                printf("\n");
            }
            printf("\n");
        }
    }
    return 0;
}
