"""Summarize finite_alphabet_mc.md: per configuration, the adapted receiver's gap on each channel and
its worst case over the Doppler-spread channels; plus the per-symbol GLRT penalty.

Run with `python3 -I summarize_mc.py results/finite_alphabet_mc.md > results/finite_alphabet_summary.md`.
"""
import re
import sys

rows = []
cn0 = None
for line in open(sys.argv[1], encoding="utf-8"):
    m = re.match(r"## C/N0 = ([+-]?\d+) dB-Hz", line)
    if m:
        cn0 = int(m.group(1))
        continue
    if not line.startswith("| ") or line.startswith("| Channel") or cn0 is None:
        continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) < 7:
        continue
    def val(c):
        m = re.match(r"(-?\d+\.\d+)", c)
        return (float(m.group(1)), "cap" in c) if m else (None, False)
    rows.append({"cn0": cn0, "chan": cells[0], "cfg": cells[2],
                 "wpm": val(cells[3]), "glrt": val(cells[4]), "band": val(cells[5]), "coh": val(cells[6])})

spread_chans = ["Gauss 0.1 Hz", "Gauss 1 Hz", "Gauss 10 Hz", "Gauss 30 Hz", "Two modes 1 Hz at ±5 Hz"]
other_chans = ["Stable phase", "Rician K=1, 1 Hz"]
print("# Finite-alphabet summary\n")
print("Generated by `summarize_mc.py` from `finite_alphabet_mc.md`. Gap (dB of extra time versus the bound) of the")
print("adapted weighted-periodogram receiver. `worst spread` is the maximum over the Gaussian 0.1–30 Hz and two-mode")
print("channels; `cap` marks alphabet-limited rates (log2 M per dwell). GLRT excess is the median (maximum) extra loss of")
print("the per-symbol spread GLRT over the adapted receiver on the same configuration; n/s means the GLRT rate was not resolved.\n")
for c in sorted(set(r["cn0"] for r in rows)):
    print(f"## C/N0 = {c:+d} dB-Hz\n")
    hdr = ["spacing / dwell (M)"] + spread_chans + ["worst spread"] + other_chans + ["GLRT excess"]
    print("| " + " | ".join(hdr) + " |")
    print("|---|" + "---:|" * (len(hdr) - 1))
    cfgs = []
    for r in rows:
        if r["cn0"] == c and r["cfg"] not in cfgs:
            cfgs.append(r["cfg"])
    for cfg in cfgs:
        cells = [cfg]
        worst = None
        excess = []
        for ch in spread_chans + other_chans:
            r = next((x for x in rows if x["cn0"] == c and x["cfg"] == cfg and x["chan"] == ch), None)
            if r is None or r["wpm"][0] is None:
                cells.append("—")
                continue
            v, cap = r["wpm"]
            cells.append(f"{v:.2f}{' cap' if cap else ''}")
            if ch in spread_chans:
                worst = v if worst is None else max(worst, v)
            if r["glrt"][0] is not None:
                excess.append(r["glrt"][0] - v)
            elif ch in spread_chans:
                excess.append(float("inf"))
        cells.insert(1 + len(spread_chans), "—" if worst is None else f"{worst:.2f}")
        if excess:
            excess.sort()
            med = excess[len(excess) // 2]
            fin = [e for e in excess if e != float("inf")]
            mx = "n/s" if len(fin) < len(excess) else f"{max(fin):.1f}"
            cells.append(("n/s" if med == float("inf") else f"{med:.1f}") + f" ({mx})")
        else:
            cells.append("—")
        print("| " + " | ".join(cells) + " |")
    print()
    band = [r for r in rows if r["cn0"] == c and r["band"][0] is not None]
    if band:
        print("Unweighted band-energy (FT8-style when the dwell equals 1/spacing) receiver where resolved:\n")
        print("| channel | spacing / dwell | BAND gap | adapted WP gap |")
        print("|---|---|---:|---:|")
        for r in band:
            print(f"| {r['chan']} | {r['cfg']} | {r['band'][0]:.2f} | {r['wpm'][0]:.2f} |")
        print()
