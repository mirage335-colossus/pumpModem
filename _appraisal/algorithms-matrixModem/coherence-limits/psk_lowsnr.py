"""Low-SNR efficiency of differential / block-detected PSK relative to the peak-limited bound.

Stdlib only; run with `python3 -I psk_lowsnr.py > results/psk_lowsnr.md`.

Model: constant-envelope PSK, symbols of duration T, matched (integrate-and-dump) symbol outputs
z_i = x_i h_i + n_i with Gaussian Doppler fading (2sigma spread W) and N0 = 1. A block of N symbols
is detected jointly with unknown channel (N = 2 is ordinary differential detection; larger N is
multiple-symbol differential detection, MSDD). In the low-SNR limit the mutual information of a
zero-mean Gaussian mixture is I ~ (1/2) E_x ||C_x - mean C||_F^2, which for random-phase PSK gives
    I_N = sum_{d=1}^{N-1} (N - d) |R[d]|^2        [nat per block]
where R[d] is the cross-covariance of symbol outputs d apart. The result is identical for BPSK and
QPSK in this limit. The bound's low-SNR rate is (P^2/2) Int S^2. Both scale with P^2, so the ratio
is a pure number: the fraction of the bound's rate, and 10*log10 of its inverse is the extra time
(about twice the equivalent power penalty). Non-overlapping blocks are assumed (one reference per
block). Also shown: the tone with single-bin coherent energy over T (`COH`) in the same limit,
whose information is |R[0]|^2/2 per symbol, and the weighted periodogram, which tends to 1.
"""
import math

SQPI = math.sqrt(math.pi)


def rho(tau):  # Gaussian Doppler spectrum with sigma = 1 Hz
    return math.exp(-2 * math.pi ** 2 * tau * tau)


def R(d, T, n=400):
    # (1/T) * Int_{-T}^{T} (T - |u|) rho(u + d T) du  (per unit P)
    h = 2 * T / n
    s = 0.0
    for i in range(n + 1):
        u = -T + i * h
        w = 1 if i in (0, n) else (4 if i % 2 else 2)
        s += w * (T - abs(u)) * rho(u + d * T)
    return s * h / 3 / T


def bound():  # (1/2) Int S^2 for sigma = 1
    return 0.5 / (2 * SQPI)


def eff_block(N, T):
    I = sum((N - d) * R(d, T) ** 2 for d in range(1, N))
    return I / (N * T) / bound()


def eff_coh(T):
    return 0.5 * R(0, T) ** 2 / T / bound()


def best(f):
    grid = [10 ** (k / 40) for k in range(-120, 41)]  # T*sigma from 0.001 to 10
    vals = [(f(t), t) for t in grid]
    return max(vals)


print("# Low-SNR efficiency of block-differential PSK versus the bound\n")
print("Generated by `psk_lowsnr.py`. Fraction of the bound's rate reached in the low-SNR (quadratic) limit for a")
print("Gaussian Doppler spectrum, optimized over symbol duration T. `2σ·T` is the optimum symbol duration in units")
print("of 1/(2σ). The extra-time column is 10·log10(1/fraction); the equivalent power penalty is about half.\n")
print("| Detector | fraction of bound | extra time (dB) | optimum 2σ·T |")
print("|---|---:|---:|---:|")
for N in (2, 3, 4, 8, 16, 32, 64):
    e, t = best(lambda T: eff_block(N, T))
    label = "Differential PSK (N = 2)" if N == 2 else f"Block / MSDD, N = {N}"
    print(f"| {label} | {e:.3f} | {10*math.log10(1/e):.2f} | {2*t:.3g} |")
e, t = best(eff_coh)
print(f"| Tone, single coherent bin over T (COH) | {e:.3f} | {10*math.log10(1/e):.2f} | {2*t:.3g} |")
print("| Tone, weighted periodogram, long dwell | → 1 | → 0 | long |")
