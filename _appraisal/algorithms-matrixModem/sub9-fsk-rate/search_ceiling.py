#!/usr/bin/env python3
"""Matrix Modem FSK below 9 kHz: hypotheses a receiver can afford against hypotheses it needs,
by tone length.

Arithmetic on the measured decode times (read from results/decode_bench.md for the local Ryzen 5
PRO 5650U, results/gpu/decode_bench_pod.out for the pod's host CPU and results/gpu/decode_gpu.out
for the RTX PRO 6000 Blackwell) and on the counting rules of calculation 18 of ../fsk-lattice
(frequency bins half the reciprocal of the window apart, drift-rate hypotheses 3.88 bins of
end-to-end drift apart, timing hypotheses an eighth of the tone apart), with one rule added from
section 8 of the specification: coherent sums over tones on different positions need the timing to
1/(8 x span), 10 ms for a 12.5 Hz span, whatever the tone length. One hypothesis is one decode of
all 2^k messages on the full window ladder (every window from two tones to the block).
Theoretical apart from the measured times; the reference classes are assumptions.

Run: python3 -I search_ceiling.py > results/search_ceiling.md
"""
import math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
FC = 8270.0
SPAN = 12.5            # Hz, total span of the positions
D0 = 5242.88           # s, the 87.4-minute block of the Monte Carlo
TONES = [0.16, 0.64, 2.56, 10.24, 40.96]   # 32768, 8192, 2048, 512, 128 tones in D0
REFS = [  # name, +-fraction of carrier, drift fraction per hour, +-timing seconds
    ("GPS-locked at both ends, corrections logged or audio re-timed from the PPS", 1e-9, 0.0, 1e-3),
    ("GPS-disciplined, corrections slewed unseen at up to 1 ppm", 1e-6, 1e-6, 1e-3),
    ("TCXO, +-1 ppm, 0.1 ppm/h, +-0.1 s", 1e-6, 1e-7, 0.1),
    ("Crystal, +-20 ppm, 1 ppm/h, +-1 s", 2e-5, 1e-6, 1.0),
    ("Sound-card clock, +-100 ppm, 5 ppm/h, +-1 s", 1e-4, 5e-6, 1.0),
]


def read_cpu(path):
    """{k: {'energy': decodes/s, tones: seconds per full-ladder decode}}"""
    out = {}; k = None; table = None
    for line in open(path):
        m = re.match(r"## k = (\d+) bits", line)
        if m: k = int(m.group(1)); out[k] = {}; table = None; continue
        m = re.match(r"Per-tone \(energy\) decode: ([0-9.e+-]+) s per decode", line)
        if m and k: out[k]["energy"] = 1 / float(m.group(1)); continue
        if line.startswith("| tones in the block"): table = "ladder"; continue
        if line.startswith("| windows W"): table = "table"; continue
        m = re.match(r"\| (\d+) \| \d+ \| ([0-9.e+-]+) \|", line)
        if m and k and table == "ladder": out[k][int(m.group(1))] = float(m.group(2))
    return out


def read_gpu(path):
    out = {24: {}}
    for line in open(path):
        m = re.match(r"energy\s+[0-9.]+ ms/call\s+([0-9.]+) decodes/s", line)
        if m: out[24]["energy"] = float(m.group(1))
        m = re.match(r"ladder\s+(\d+) tones\s+([0-9.]+) ms/decode", line)
        if m: out[24][int(m.group(1))] = float(m.group(2)) / 1000
    for k in (16, 10):  # not measured on the GPU: scaled from 24 bits by the message count
        out[k] = {key: (v * 2 ** (24 - k) if key == "energy" else v / 2 ** (24 - k)) for key, v in out[24].items()}
    return out


pod_threads = "?"; pod_cpu = "pod host CPU"
for line in open(os.path.join(HERE, "results/gpu/identity.out")):
    if line.startswith("Model name:"): pod_cpu = line.split(":", 1)[1].strip().replace(" Processor", "")
    if line.startswith("threads used by decode_bench:"): pod_threads = line.split(":", 1)[1].strip()
DEV = {
    "Ryzen 5 PRO 5650U, 12 threads": read_cpu(os.path.join(HERE, "results/decode_bench.md")),
    "%s, %s threads" % (pod_cpu, pod_threads): read_cpu(os.path.join(HERE, "results/gpu/decode_bench_pod.out")),
    "RTX PRO 6000 Blackwell": read_gpu(os.path.join(HERE, "results/gpu/decode_gpu.out")),
}
LAPTOP, GPU = list(DEV)[0], list(DEV)[2]


def fmt(x):
    if x >= 1e6: return "%.2g" % x
    if x >= 100: return "{:,.0f}".format(x)
    if x >= 10: return "%.0f" % x
    if x >= 1: return "%.1f" % x
    return "%.2g" % x


def need(ref, D, T):
    _, df, dr, tau = ref
    F, Fdot = df * FC, dr * FC / 3600.0
    nf = max(1, math.ceil(4 * F * D)); nd = max(1, math.ceil(2 * Fdot * D * D / 3.88))
    nt = max(1, math.ceil(2 * tau / (T / 8)), math.ceil(2 * tau * 8 * SPAN - 1e-9))
    return nf, nd, nt


def sec(dev, k, T): return DEV[dev][k][round(D0 / T)]


print("# Sub-9 kHz FSK rate and spacing: affordable against needed hypotheses, by tone length\n")
print("Generated by `search_ceiling.py` from the measured decode times in `results/decode_bench.md` and")
print("`results/gpu/`. Carrier 8,270 Hz, span 12.5 Hz. One hypothesis is one decode of all 2^k messages on the")
print("full window ladder. Counting rules of calculation 18 of `../fsk-lattice` plus the 1/(8 x span) timing rule.")
print("Theoretical apart from the measured times. GPU figures for 16 and 10 bits are scaled from its 24-bit")
print("measurement by the message count; every CPU figure is measured for its own block size.\n")

print("## 1. What one decode costs, and how many fit into the block's own duration\n")
print("An 87.4-minute block holds 32,768 / 8,192 / 2,048 / 512 / 128 tones of 0.16 / 0.64 / 2.56 / 10.24 / 40.96 s,")
print("the tone counts that were timed. The full ladder costs one lookup per message and tone, so a longer block")
print("at the same tone length takes longer in proportion and the number that fits into it stays the same.\n")
for k in (24, 16, 10):
    print("### %d-bit block\n" % k)
    print("| device | tone 0.16 s (6.25/s) | 0.64 s (1.56/s) | 2.56 s (0.39/s) | 10.24 s (0.098/s) | 40.96 s (0.024/s) | per-tone decode only |")
    print("|---|---:|---:|---:|---:|---:|---:|")
    for dev in DEV:
        cells = ["%s s; %s" % (fmt(sec(dev, k, T)), fmt(D0 / sec(dev, k, T))) for T in TONES]
        e = DEV[dev][k]["energy"]
        print("| %s%s | %s | %s s; %s |" % (dev, " (scaled)" if dev == GPU and k != 24 else "", " | ".join(cells), fmt(1 / e), fmt(D0 * e)))
    print("\nEntries: seconds per full-ladder decode of an 87.4-minute block; decodes that fit into 87.4 minutes.\n")

print("## 2. Hypotheses needed\n")
print("Frequency bins x drift-rate bins x timing offsets for a whole-block coherent window. The sample clock is")
print("taken from the same reference as the carrier, so its rate follows the frequency hypothesis. Timing offsets")
print("are the larger of the timing uncertainty over an eighth of the tone (per-tone reception) and over")
print("1/(8 x span) = 10 ms for the 12.5 Hz span (coherent sums across positions). The second rule governs for")
print("every tone length here, so the count does not depend on the tone.\n")
for D, dn in ((D0, "87.4 min"), (4 * D0, "5.8 h")):
    print("### Block of %s\n" % dn)
    print("| reference at each end | frequency x drift | timing offsets | hypotheses |")
    print("|---|---:|---:|---:|")
    for ref in REFS:
        rows = [need(ref, D, T) for T in TONES]
        assert len(set(rows)) == 1
        nf, nd, nt = rows[0]
        print("| %s | %s x %s | %d | %s |" % (ref[0], fmt(nf), fmt(nd), nt, fmt(nf * nd * nt)))
    print()
print("The count grows with the cube of the window (frequency bins with D, drift-rate bins with D^2), and with the")
print("timing uncertainty times the span. A span of 25 or 50 Hz doubles or quadruples the timing offsets.\n")

print("## 3. Margin: affordable divided by needed (87.4-minute block)\n")
print("Above 1 the receiver keeps up with the transmitter on that device; below 1 it falls behind by that factor.\n")
for k in (24, 10):
    for dev in (LAPTOP, GPU):
        print("### %d-bit block, %s%s\n" % (k, dev, " (scaled from 24 bits)" if dev == GPU and k != 24 else ""))
        print("| reference at each end | 0.16 s tone | 0.64 s | 2.56 s | 10.24 s | 40.96 s |")
        print("|---|---:|---:|---:|---:|---:|")
        for ref in REFS:
            cells = []
            for T in TONES:
                nf, nd, ntm = need(ref, D0, T); cells.append(fmt(D0 / sec(dev, k, T) / (nf * nd * ntm)))
            print("| %s | %s |" % (ref[0], " | ".join(cells)))
        print()

print("## 4. The same margin if the frequency bins come from a transform across tone sums\n")
print("Derived, not measured. A transform across a message's tone (or short-window) sums gives every frequency")
print("bin inside +-1/(4 T) of the tone length T at once, at a cost taken here as 20 plain decodes (an assumption).")
print("Frequency then needs ceil(4 F T) such decodes in place of 4 F D plain ones; drift and timing are unchanged.\n")
for k in (24, 10):
    print("### %d-bit block, %s\n" % (k, LAPTOP))
    print("| reference at each end | 0.16 s tone | 0.64 s | 2.56 s | 10.24 s | 40.96 s |")
    print("|---|---:|---:|---:|---:|---:|")
    for ref in REFS:
        cells = []
        for T in TONES:
            nf, nd, ntm = need(ref, D0, T); F = ref[1] * FC; nf2 = max(1, math.ceil(4 * F * T)); cost = 1 if nf == 1 else 20
            cells.append(fmt(D0 / sec(LAPTOP, k, T) / (min(nf, nf2 * cost) * nd * ntm)))
        print("| %s | %s |" % (ref[0], " | ".join(cells)))
    print()
